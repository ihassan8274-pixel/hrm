-- Anonymous, redacted frontend error reports. Deliberately no user id, IP,
-- headers, cookies or tokens; operators read these rows directly in payroll.
CREATE TABLE IF NOT EXISTS client_errors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 500),
  stack TEXT CHECK (stack IS NULL OR char_length(stack) <= 4000),
  url TEXT CHECK (url IS NULL OR char_length(url) <= 300),
  level TEXT NOT NULL DEFAULT 'error' CHECK (level IN ('error', 'warn', 'info')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_client_errors_created_at ON client_errors (created_at DESC);
