-- شروط التوظيف في استمارة طلب التوظيف: فترة تجربة 90 يوماً قابلة
-- للتمديد لمدة مماثلة، وحق الشركة في تشغيل العامل بأي فرع تابع لخطة الشركة.
--
-- الزرع الأصلي يستخدم ON CONFLICT DO NOTHING، لذلك لا يكفي تعديل ملف القالب.
-- التعديل يتم بـ replace حول نقاط ثابتة ليبقى أي تعديل أجراه المسؤول على بقية
-- النص، ويتكرر استدعاء الـmigration بأمان لأن الشرط يمنع الإدراج المزدوج.
UPDATE document_templates
SET body_ar = replace(
      replace(body_ar, 'إقرار المتقدم', 'إقرار المتقدم وشروط التوظيف'),
      'اسم المتقدم: ______________',
      'أولاً — فترة التجربة
يخضع الموظف لفترة تجربة مدتها 90 يوماً من تاريخ المباشرة، وللشركة تمديدها لمدة مماثلة إذا رأت ذلك من مصلحة العمل، وفق نظام العمل السعودي ولائحة {{company.name}} المعتمدة.

ثانياً — التنقل بين الفروع
للشركة الحق في تشغيل العامل في أي فرع من فروعها التابعة، ونقله بينها وفق خطتها التشغيلية ومقتضيات العمل، بما لا يمسّ بحقوقه المقررة نظامياً.

اسم المتقدم: ______________'
    )
WHERE template_key = 'job_application_form'
  AND body_ar LIKE '%إقرار المتقدم%'
  AND body_ar LIKE '%اسم المتقدم: ______________%'
  AND body_ar NOT LIKE '%فترة التجربة%';
