-- Development chain, payroll approval and final settlement.
--
-- Training was the only lifecycle stage with no table at all. Enrollments are
-- the real record that connects an appraisal recommendation to a promotion.
-- Payroll rows gain an explicit decision (NULL means a legacy row generated
-- before this migration, which stays exportable) and a final-settlement link.

CREATE TABLE IF NOT EXISTS training_courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  category TEXT,
  duration_hours NUMERIC(6,2) DEFAULT 0,
  target_position TEXT,
  status TEXT DEFAULT 'active',
  created_by TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS training_enrollments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
  course_id BIGINT REFERENCES training_courses (id) ON DELETE SET NULL,
  appraisal_id BIGINT REFERENCES appraisals (id) ON DELETE SET NULL,
  source TEXT DEFAULT 'manual',
  status TEXT DEFAULT 'recommended',
  score NUMERIC(5,2),
  completed_at TIMESTAMPTZ,
  certificate_number TEXT,
  created_by TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_training_enrollments_employee ON training_enrollments (employee_id, status);
CREATE INDEX IF NOT EXISTS idx_training_enrollments_appraisal ON training_enrollments (appraisal_id);

-- A promotion is a decision, not an immediate salary write. NULL keeps old
-- promotions readable as already-effective; new ones start pending.
ALTER TABLE promotions ADD COLUMN IF NOT EXISTS training_enrollment_id BIGINT;
ALTER TABLE promotions ADD COLUMN IF NOT EXISTS appraisal_id BIGINT;
ALTER TABLE promotions ADD COLUMN IF NOT EXISTS approval_status TEXT DEFAULT 'approved';
ALTER TABLE promotions ADD COLUMN IF NOT EXISTS approved_by TEXT;
ALTER TABLE promotions ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ;

-- NULL approval_status is deliberately not backfilled: it marks a legacy payslip
-- created before the approval gate existed, so historical WPS files stay intact.
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS approval_status TEXT;
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS approved_by TEXT;
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ;
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS payment_status TEXT DEFAULT 'pending';
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS paid_at TIMESTAMPTZ;
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS eos_amount NUMERIC(14,2) DEFAULT 0;
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS is_final_settlement INTEGER DEFAULT 0;
ALTER TABLE payroll ADD COLUMN IF NOT EXISTS final_settlement_id BIGINT;

CREATE INDEX IF NOT EXISTS idx_payroll_approval ON payroll (month, year, approval_status);

ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS settlement_status TEXT DEFAULT 'draft';
ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS final_payroll_id BIGINT;
ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS final_payroll_month INTEGER;
ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS final_payroll_year INTEGER;
ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS approved_by TEXT;
ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ;
ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS paid_at TIMESTAMPTZ;
ALTER TABLE eos_calculations ADD COLUMN IF NOT EXISTS wps_exported_at TIMESTAMPTZ;
