-- طلبات الخدمة الذاتية (بوابة الموظف):
--   * جدول المقترحات وتوصيات تطوير سير العمل.
--   * ربط طلب الاعتماد بالسجل الأصلي، حتى تنعكس نتيجة الاعتماد عليه.
CREATE TABLE IF NOT EXISTS employee_suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL,
  suggestion_type TEXT DEFAULT 'suggestion',
  title TEXT,
  details TEXT,
  category TEXT,
  expected_impact TEXT,
  status TEXT DEFAULT 'submitted',
  hr_response TEXT,
  responded_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (employee_id) REFERENCES employees (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_employee_suggestions_employee ON employee_suggestions(employee_id);

ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS entity_type TEXT;
ALTER TABLE approval_requests ADD COLUMN IF NOT EXISTS entity_id INTEGER;
