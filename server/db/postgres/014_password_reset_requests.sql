-- Public password-recovery requests are staged for administrator review only.
-- The public route never reveals whether an account exists, never creates a
-- session, and never stores a clear-text password. An administrator issues a
-- temporary password through the existing admin-only credential route, then
-- closes the request here.
CREATE TABLE IF NOT EXISTS password_reset_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  username TEXT NOT NULL,
  contact_email TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ,
  reviewed_by BIGINT,
  review_note TEXT,
  FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_password_reset_requests_status
  ON password_reset_requests (status, created_at DESC);
